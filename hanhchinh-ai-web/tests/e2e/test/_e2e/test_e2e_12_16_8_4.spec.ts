// 12.16.8.4.5
// CITATION SCORE / METADATA
// ============================================================

test(
  "12.16.8.4.5 - citation score and metadata are valid",
  async ({ page }) => {
    await openAssistant(page);

    const {
      response,
      body,
    } =
      await getAssistantResponseBody(
        page,
      );

    expect(
      response.status(),
    ).toBe(200);

    const citations =
      getCitations(body);

    expect(
      citations.length,
    ).toBeGreaterThanOrEqual(1);

    const citation =
      citations[0];

    /*
     * Score là metadata similarity của nguồn.
     * Một số runtime có thể expose score ở
     * citation hoặc metadata; không ép kiểu
     * quá mức để giữ compatibility.
     */
    if (
      citation.score !==
      undefined &&
      citation.score !== null
    ) {
      expect(
        typeof citation.score,
      ).toBe("number");
    }

    if (
      citation.metadata !==
      undefined
    ) {
      expect(
        typeof citation.metadata,
      ).toBe("object");

      expect(
        citation.metadata,
      ).not.toBeNull();
    }

    expect(
      typeof body.metadata,
    ).toBe("object");

    expect(
      body.metadata,
    ).not.toBeNull();

    const citationCount =
      body.metadata?.citation_count;

    if (
      citationCount !==
        undefined &&
      citationCount !== null
    ) {
      expect(
        Number(citationCount),
      ).toBeGreaterThanOrEqual(1);
    }
  },
);

