import {
  test,
  expect,
  type Page,
  type Response,
} from "@playwright/test";

// ============================================================
// CONSTANTS
// ============================================================

const BASE_URL =
  process.env.E2E_BASE_URL ||
  "http://localhost:5173";

const ASSISTANT_PATH = "/assistant";

const CITATION_QUESTION =
  "Chuyển đổi số là gì?";

const CITATION_SECOND_QUESTION =
  "Triển khai chuyển đổi số cần gắn với những nội dung nào?";

// ============================================================
// TYPES
// ============================================================

interface AssistantCitation {
  citation_id?: string;
  source?: string;
  document_id?: string | null;
  page_number?: number | null;
  chunk_index?: number | null;
  content?: string;
  label?: string;
  score?: number | null;
  metadata?: Record<string, unknown>;
  [key: string]: unknown;
}

interface AssistantResponse {
  success?: boolean;
  answer?: string;
  question?: string;
  query?: string;
  citations?: AssistantCitation[];
  metadata?: Record<string, unknown>;
  message?: string;
  [key: string]: unknown;
}

// ============================================================
// HELPERS
// ============================================================

async function openAssistant(
  page: Page,
): Promise<void> {
  await page.goto(
    `${BASE_URL}${ASSISTANT_PATH}`,
    {
      waitUntil: "networkidle",
    },
  );

  await expect(
    page.locator("body"),
  ).toContainText(
    /Trợ lý Hành Chính AI|Trợ lý AI|Assistant/i,
  );
}

async function getAssistantInput(
  page: Page,
) {
  const textarea =
    page.locator("textarea").first();

  if (
    (await textarea.count()) > 0 &&
    (await textarea.isVisible())
  ) {
    return textarea;
  }

  const textboxes =
    page.getByRole("textbox");

  const count =
    await textboxes.count();

  for (
    let index = count - 1;
    index >= 0;
    index -= 1
  ) {
    const textbox =
      textboxes.nth(index);

    if (
      await textbox.isVisible()
    ) {
      return textbox;
    }
  }

  throw new Error(
    "Không tìm thấy ô nhập câu hỏi Assistant.",
  );
}

async function submitAssistantQuestionAndCaptureResponse(
  page: Page,
  question: string,
): Promise<Response> {
  const input =
    await getAssistantInput(page);

  await input.fill(question);

  await expect(
    input,
  ).toHaveValue(question);

  const sendButton =
    page.getByRole(
      "button",
      {
        name: /gửi|send|hỏi/i,
      },
    ).first();

  await expect(
    sendButton,
  ).toBeVisible();

  await expect(
    sendButton,
  ).toBeEnabled();

  const responsePromise =
    page.waitForResponse(
      (response) => {
        const url =
          response.url().toLowerCase();

        return (
          url.includes("/assistant/ask") &&
          response.request().method() ===
            "POST"
        );
      },
      {
        timeout: 30_000,
      },
    );

  await sendButton.click();

  return responsePromise;
}

async function getAssistantResponseBody(
  page: Page,
  question: string = CITATION_QUESTION,
): Promise<{
  response: Response;
  body: AssistantResponse;
}> {
  const response =
    await submitAssistantQuestionAndCaptureResponse(
      page,
      question,
    );

  const body =
    (await response.json()) as AssistantResponse;

  return {
    response,
    body,
  };
}

function getCitations(
  body: AssistantResponse,
): AssistantCitation[] {
  expect(
    Array.isArray(body.citations),
  ).toBeTruthy();

  return body.citations ?? [];
}

function getCitationCount(
  body: AssistantResponse,
): number {
  const citations =
    getCitations(body);

  return citations.length;
}

