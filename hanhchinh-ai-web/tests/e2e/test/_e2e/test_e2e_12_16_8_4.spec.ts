// 12.16.8.4.6
// CITATION IS RENDERED IN UI
// ============================================================

test(
  "12.16.8.4.6 - citation data is rendered in UI",
  async ({ page }) => {
    await openAssistant(page);

    const response =
      await submitAssistantQuestionAndCaptureResponse(
        page,
        CITATION_QUESTION,
      );

    expect(
      response.status(),
    ).toBe(200);

    const body =
      (await response.json()) as AssistantResponse;

    const citations =
      getCitations(body);

    expect(
      citations.length,
    ).toBeGreaterThanOrEqual(1);

    /*
     * Chờ Assistant hoàn tất render.
     */
    await expect(
      page.locator("body"),
    ).not.toContainText(
      /đang xử lý|loading/i,
      {
        timeout: 30_000,
      },
    );

    /*
     * UI phải hiển thị ít nhất một dấu hiệu
     * của citation/source. Không hard-code một
     * class CSS cụ thể.
     */
    await expect(
      page.locator("body"),
    ).toContainText(
      /nguồn|trích dẫn|citation|tài liệu|tham khảo/i,
      {
        timeout: 30_000,
      },
    );

    const citation =
      citations[0];

    const sourceText =
      citation.source ||
      citation.document_id ||
      citation.label;

    if (sourceText) {
      await expect(
        page.locator("body"),
      ).toContainText(
        String(sourceText),
        {
          timeout: 30_000,
        },
      );
    }
  },
);

// ============================================================
// 12.16.8.4.7
// FINAL CITATION FLOW GATE
// ============================================================

test(
  "12.16.8.4.7 - final citation flow gate",
  async ({ page }) => {
    const pageErrors: string[] = [];

    page.on(
      "pageerror",
      (error) => {
        pageErrors.push(
          error.message,
        );
      },
    );

    await openAssistant(page);

    const {
      response,
      body,
    } =
      await getAssistantResponseBody(
        page,
        CITATION_SECOND_QUESTION,
      );

    expect(
      response.status(),
    ).toBe(200);

    expect(
      response.ok(),
    ).toBeTruthy();

    expect(
      typeof body.answer,
    ).toBe("string");

    expect(
      body.answer.trim().length,
    ).toBeGreaterThan(0);

    const returnedQuestion =
      body.question ??
      body.query;

    expect(
      returnedQuestion,
    ).toBe(
      CITATION_SECOND_QUESTION,
    );

    const citations =
      getCitations(body);

    expect(
      citations.length,
    ).toBeGreaterThanOrEqual(1);

    for (
      const citation of citations
    ) {
      expect(
        typeof citation,
      ).toBe("object");

      expect(
        citation,
      ).not.toBeNull();

      expect(
        citation.citation_id ||
          citation.label,
      ).toBeTruthy();

      expect(
        citation.source ||
          citation.document_id,
      ).toBeTruthy();

      if (
        citation.content !==
        undefined
      ) {
        expect(
          String(
            citation.content,
          ).trim().length,
        ).toBeGreaterThan(0);
      }
    }

    expect(
      typeof body.metadata,
    ).toBe("object");

    expect(
      body.metadata,
    ).not.toBeNull();

    const citationCount =
      body.metadata?.citation_count;

    if (
      citationCount !==
        undefined &&
      citationCount !== null
    ) {
      expect(
        Number(citationCount),
      ).toBeGreaterThanOrEqual(1);
    }

    expect(
      pageErrors,
    ).toEqual([]);
  },
);